#!/usr/bin/env node
// Generate Swift source holding the official tool descriptions and JSON Schemas.
//
// Tool schemas must be byte-identical to what the model receives, so they are
// *generated* from the extracted catalog rather than typed by hand — the same reason
// the official repo generates `docs/tool-catalog.md` by booting each plugin.
//
// Usage: node Tools/gen-tool-schemas.mjs Spec/tool-catalog.schemas.json Sources/HarnessCore/Tools/Generated/ToolSchemas.swift

import { readFileSync, writeFileSync, mkdirSync } from 'node:fs';
import { dirname, resolve } from 'node:path';

const [, , catalogPath, outPath] = process.argv;
if (!catalogPath || !outPath) {
  console.error('usage: gen-tool-schemas.mjs <catalog.json> <out.swift>');
  process.exit(2);
}

const catalog = JSON.parse(readFileSync(resolve(catalogPath), 'utf8'));
const tools = catalog.tools.filter((t) => t.parameters);

/**
 * Swift string literal with every special character escaped.
 *
 * Raw literals (`#"..."#`) were the first attempt and are wrong here: a single-line
 * string literal — raw or not — cannot contain a literal newline, and several tool
 * descriptions are multi-line prose. Escaping keeps each literal on one line.
 */
function swiftLiteral(text) {
  const escaped = text
    .replace(/\\/g, '\\\\')
    .replace(/"/g, '\\"')
    .replace(/\r/g, '\\r')
    .replace(/\n/g, '\\n')
    .replace(/\t/g, '\\t')
    // Any remaining C0/C1 control character goes out as an escape.
    .replace(/[\u0000-\u0008\u000B\u000C\u000E-\u001F\u007F]/g, (ch) => `\\u{${ch.codePointAt(0).toString(16).toUpperCase()}}`);
  return `"${escaped}"`;
}

const lines = [];
lines.push('// GENERATED by Tools/gen-tool-schemas.mjs — do not edit by hand.');
lines.push('//');
lines.push('// Source: Spec/tool-catalog.schemas.json, extracted from the official generated');
lines.push('// catalog (official-dsh/docs/tool-catalog.md), whose generator BOOTS');
lines.push(`// each tool plugin and reads ctx.tools.schemas(). ${tools.length} tools.`);
lines.push('//');
lines.push('// Regenerate after a harness upgrade with:');
lines.push('//   node Tools/extract-tool-catalog.mjs official-dsh/docs/tool-catalog.md Spec/tool-catalog.schemas.json');
lines.push('//   node Tools/gen-tool-schemas.mjs Spec/tool-catalog.schemas.json Sources/HarnessCore/Tools/Generated/ToolSchemas.swift');
lines.push('');
lines.push('import Foundation');
lines.push('import HarnessKit');
lines.push('');
lines.push('/// The model-facing definition of every shipped tool, verbatim from the official');
lines.push('/// runtime.');
lines.push('public enum OfficialToolSchemas {');
lines.push(`  public static let toolCount = ${tools.length}`);
lines.push('');
lines.push('  /// `name` → the exact description string the model receives.');
lines.push('  public static let descriptions: [String: String] = [');
for (const tool of tools) {
  lines.push(`    ${JSON.stringify(tool.name)}: ${swiftLiteral(tool.description)},`);
}
lines.push('  ]');
lines.push('');
lines.push('  /// `name` → the exact JSON Schema text the model receives.');
lines.push('  public static let parameterJSON: [String: String] = [');
for (const tool of tools) {
  lines.push(`    ${JSON.stringify(tool.name)}: ${swiftLiteral(JSON.stringify(tool.parameters))},`);
}
lines.push('  ]');
lines.push('');
lines.push('  /// `name` → the package that contributes the tool, for diagnostics.');
lines.push('  public static let packages: [String: String] = [');
for (const tool of tools) {
  lines.push(`    ${JSON.stringify(tool.name)}: ${JSON.stringify(tool.package ?? '')},`);
}
lines.push('  ]');
lines.push('');
lines.push('  public static func description(for name: String) -> String? { descriptions[name] }');
lines.push('');
lines.push('  /// Parsed parameters, or `nil` when this build has no official schema for the');
lines.push('  /// tool (e.g. a native-only helper).');
lines.push('  public static func parameters(for name: String) -> JSONValue? {');
lines.push('    guard let text = parameterJSON[name] else { return nil }');
lines.push('    return try? JSONValue.parse(text, context: "schema:\\(name)")');
lines.push('  }');
lines.push('');
lines.push('  public static var allNames: [String] { descriptions.keys.sorted() }');
lines.push('');
lines.push('  /// Build a descriptor for a native tool implementation. The description and');
lines.push('  /// schema come from the catalog when present, so a conformance test can assert');
lines.push('  /// byte equality without the implementation repeating the JSON.');
lines.push('  public static func descriptor(for name: String, origin: ToolOrigin = .model, isMutating: Bool) -> ToolDescriptor {');
lines.push('    ToolDescriptor(');
lines.push('      name: name,');
lines.push('      description: descriptions[name] ?? "",');
lines.push('      parameters: parameters(for: name) ?? .object(["type": .string("object")]),');
lines.push('      category: ToolCategory(name: name),');
lines.push('      origin: origin,');
lines.push('      isMutating: isMutating');
lines.push('    )');
lines.push('  }');
lines.push('}');
lines.push('');

mkdirSync(dirname(resolve(outPath)), { recursive: true });
writeFileSync(resolve(outPath), lines.join('\n'));
console.log(`wrote ${outPath} (${tools.length} tools)`);
